// Writes the CSS custom properties both surfaces read, from src/tokens.ts,
// and the SVG icons and logos every app serves, from src/icon.ts.
//
//   node scripts/generate.mjs          write them
//   node scripts/generate.mjs --check  fail if any is stale
//
// The icons land in each app's own static folder, because that is where a
// browser, Next.js and Mintlify each look for them. The PNGs, the .ico and
// the social cards need a browser to draw, so apps/home/og/render.mjs makes
// those (`pnpm --filter @airship/home media`).
//
// The output is deterministic: regenerating without a token change writes
// the same bytes.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { iconSvg, wordmarkSvg } from "../src/icon.ts";
import {
  cloud,
  font,
  halftone,
  motion,
  palette,
  radius,
  shadow,
  shell,
  signal,
  syntax,
  theme,
} from "../src/tokens.ts";

const HEADER = (what) => `/*
 * GENERATED by packages/tokens/scripts/generate.mjs from src/tokens.ts.
 * Do not edit: change the token and run \`pnpm --filter @airship/tokens generate\`.
 *
 * ${what}
 */
`;

const kebab = (name) =>
  name
    .replace(/([a-z])([A-Z0-9])/g, "$1-$2")
    .replace(/([0-9])([A-Za-z])/g, "$1-$2")
    .toLowerCase();

const block = (selector, entries) =>
  `${selector} {\n${entries.map(([name, value]) => `  --${name}: ${value};`).join("\n")}\n}\n`;

// ── brand.css: the marketing site's names ──────────────────────────────────

const brandEntries = [
  ["bg", palette.ground],
  ["panel-bg", palette.panel],
  ["well-bg", palette.well],
  ["card-bg", palette.card],
  ["card-bg-2", palette.cardRaised],
  ["btn-dark-bg", palette.control],
  ["chip-bg", palette.chip],
  ["line", palette.line],
  ["line-faint", palette.lineFaint],
  ["halftone", palette.halftone],
  ["white", palette.white],
  ["white-80", palette.white80],
  ["white-70", palette.white70],
  ["white-50", palette.white50],
  ["white-30", palette.white30],
  ["dark-text", palette.ink],
  ...Object.entries(signal).map(([name, value]) => [`dot-${name}`, value]),
  ...Object.entries(cloud.dark).map(([name, value]) => [
    `cloud-${name}`,
    value,
  ]),
  ...Object.entries(syntax.dark).map(([name, value]) => [
    `syntax-${name}`,
    value,
  ]),
  ["font-sans", font.sans],
  ["font-mono", font.mono],
  ...Object.entries(radius).map(([name, value]) => [`radius-${name}`, value]),
  ...Object.entries(shadow).map(([name, value]) => [
    `shadow-${kebab(name)}`,
    value,
  ]),
  ["ease", motion.ease],
  ["speed-fast", motion.fast],
  ["speed-base", motion.base],
  ["speed-slow", motion.slow],
];

const brandCss = `${HEADER(
  "The marketing site's palette, under the names apps/home has always used."
)}
${block(":root", brandEntries)}`;

// ── theme.css: the dashboard's semantic roles ──────────────────────────────

// shadcn's components name the danger colour `destructive`; it is the
// text-safe danger, since they set it as text as often as a fill.
const themeEntries = (values, clouds, code) => [
  ...Object.entries(code).map(([name, value]) => [`syntax-${name}`, value]),
  ...Object.entries(values).map(([name, value]) => [kebab(name), value]),
  ["destructive", values.dangerForeground],
  ...Object.entries(clouds).map(([name, value]) => [`cloud-${name}`, value]),
];

const colorNames = [
  ...Object.keys(theme.dark).filter((name) => name !== "halftone"),
  "destructive",
  ...Object.keys(cloud.dark).map((name) => `cloud-${name}`),
  ...Object.keys(syntax.dark).map((name) => `syntax-${name}`),
].map(kebab);

const shellEntries = [
  ["radius", radius.lg],
  ["shell-inset", `${shell.inset}px`],
  ["sidebar-width", `${shell.sidebarWidth}px`],
  ["topbar-height", `${shell.topBarHeight}px`],
  ["content-width", `${shell.contentWidth}px`],
  ["ease", motion.ease],
  ["speed-fast", motion.fast],
  ["speed-base", motion.base],
  ["speed-slow", motion.slow],
];

const themeInline = [
  ...colorNames.map((name) => [`color-${name}`, `var(--${name})`]),
  ["font-sans", `var(--font-geist-sans, "Geist"), ${font.sans}`],
  ["font-mono", `var(--font-geist-mono, "Geist Mono"), ${font.mono}`],
  ...Object.entries(radius)
    .filter(([name]) => name !== "full")
    .map(([name, value]) => [`radius-${name}`, value]),
  ["radius-3xl", "20px"],
  ["radius-4xl", "24px"],
  ...Object.entries(shadow).map(([name, value]) => [
    `shadow-${kebab(name)}`,
    value,
  ]),
  ["ease-smooth", motion.ease],
  ["tracking-display", font.tracking.display],
  ["tracking-tight", font.tracking.tight],
  ["tracking-label", font.tracking.label],
];

const themeCss = `${HEADER(
  "The dashboard's theme: light on :root, dark under .dark, mapped to Tailwind."
)}
${block(":root", [...themeEntries(theme.light, cloud.light, syntax.light), ...shellEntries])}
${block(".dark", themeEntries(theme.dark, cloud.dark, syntax.dark))}
${block("@theme inline", themeInline)}
/* The halftone texture behind the landing page's hero, as a utility. */
@utility bg-halftone {
  background-image: radial-gradient(var(--halftone) ${halftone.dot}, transparent calc(${halftone.dot} + 0.2px));
  background-size: ${halftone.pitch} ${halftone.pitch};
}
`;

// ── write or check ─────────────────────────────────────────────────────────

const SVG_HEADER =
  "<!-- GENERATED by packages/tokens/scripts/generate.mjs. Do not edit. -->\n";
const favicon = SVG_HEADER + iconSvg();

const outputs = [
  ["../src/generated/brand.css", brandCss],
  ["../src/generated/theme.css", themeCss],
  ["../../../apps/home/public/favicon.svg", favicon],
  ["../../../apps/dash/src/app/icon.svg", favicon],
  ["../../../apps/docs/favicon.svg", favicon],
  ["../../../apps/docs/logo/dark.svg", SVG_HEADER + wordmarkSvg("dark")],
  ["../../../apps/docs/logo/light.svg", SVG_HEADER + wordmarkSvg("light")],
];

const check = process.argv.includes("--check");
let stale = 0;
for (const [relative, contents] of outputs) {
  const path = fileURLToPath(new URL(relative, import.meta.url));
  if (check) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {
      // A missing file is stale.
    }
    if (current !== contents) {
      console.error(`stale: ${relative.replace(/^(\.\.\/)+/, "")}`);
      stale += 1;
    }
  } else {
    writeFileSync(path, contents);
  }
}
if (stale > 0) {
  console.error("Run `pnpm --filter @airship/tokens generate` and commit.");
  process.exit(1);
}
